/**
 * Photo pipeline
 * --------------
 * Put original photographs in   photos/<category>/<descriptive-name>.jpg|png|webp
 * Run                            npm run photos
 *
 * For every original this writes responsive WebP files to
 *   public/images/<category>/<descriptive-name>-<width>.webp
 * and regenerates src/content/photos.generated.ts, which records each photo's
 * real dimensions, available widths and a tiny blurred preview (shown while
 * the full image loads). Story code never needs to change when photos do:
 * reference a photo from src/content/photos.ts by its "<category>/<name>" key.
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const SRC_DIR = path.join(ROOT, 'photos');
const OUT_DIR = path.join(ROOT, 'public', 'images');
const MANIFEST = path.join(ROOT, 'src', 'content', 'photos.generated.ts');
const WIDTHS = [480, 960, 1600];
const EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.tif', '.tiff', '.heic']);

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return EXTENSIONS.has(path.extname(entry.name).toLowerCase()) ? [full] : [];
  });
}

const files = walk(SRC_DIR).sort();
const entries = {};

for (const file of files) {
  const rel = path.relative(SRC_DIR, file).split(path.sep).join('/');
  const key = rel.replace(/\.[^.]+$/, '');
  const outBase = path.join(OUT_DIR, key);
  fs.mkdirSync(path.dirname(outBase), { recursive: true });

  // .rotate() applies EXIF orientation so phone photos are never sideways.
  const base = sharp(file).rotate();
  const meta = await base.metadata();
  const swap = (meta.orientation ?? 1) >= 5;
  const width = swap ? meta.height : meta.width;
  const height = swap ? meta.width : meta.height;

  const targets = WIDTHS.filter((w) => w < width);
  targets.push(Math.min(width, WIDTHS[WIDTHS.length - 1]));
  const widths = [...new Set(targets)].sort((a, b) => a - b);

  const srcStat = fs.statSync(file);
  const variants = [];
  for (const w of widths) {
    const out = `${outBase}-${w}.webp`;
    const fresh = fs.existsSync(out) && fs.statSync(out).mtimeMs >= srcStat.mtimeMs;
    if (!fresh) {
      await sharp(file).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: 80, effort: 5 }).toFile(out);
    }
    variants.push({ w, src: `/images/${key}-${w}.webp` });
  }

  const lqipBuffer = await sharp(file).rotate().resize({ width: 24 }).blur(1.2).webp({ quality: 40 }).toBuffer();
  entries[key] = {
    width,
    height,
    variants,
    lqip: `data:image/webp;base64,${lqipBuffer.toString('base64')}`,
  };
  console.log(`  ✓ ${key}  ${width}×${height}  →  ${widths.join(', ')}w`);
}

const banner = `/* AUTO-GENERATED by scripts/optimize-photos.mjs — do not edit by hand.
 * Run \`npm run photos\` after adding or replacing files in /photos. */\n`;
const body = `import type { GeneratedPhoto } from './types';

export const generatedPhotos: Record<string, GeneratedPhoto> = ${JSON.stringify(entries, null, 2)};\n`;
fs.writeFileSync(MANIFEST, banner + body);
console.log(`\nWrote ${Object.keys(entries).length} photos to public/images and src/content/photos.generated.ts`);
